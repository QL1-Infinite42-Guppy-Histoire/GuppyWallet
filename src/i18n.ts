export const DICT: Record<Lang, Record<I18nKey, string>> = { ja, en };

/**
 * Language mirror for non-React code. LanguageContext calls
 * setCurrentLang() whenever the app language is loaded or changed;
 * lib modules (TxJob builders, thrown error messages, price route
 * labels) read strings through tr() so their output matches the UI
 * language without threading a translator through every signature.
 */
let currentLang: Lang = "ja";

export function setCurrentLang(lang: Lang): void {
  currentLang = lang;
}

export function tr(key: I18nKey): string {
  return DICT[currentLang][key] ?? DICT.ja[key] ?? key;
}
